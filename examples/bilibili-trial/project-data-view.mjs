import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { createPromptManagerTools } from '../../lib/index.js'
import { collectSchemaRefs, typeRefUri } from '../../lib/engine/contracts.js'

const architecture = JSON.parse(await readFile(new URL('./architecture.json', import.meta.url), 'utf8'))
const timestamp = new Date().toISOString()
const text = (zh, en) => ({ zh, en })
const module = (id, name, description, extra = {}) => ({
  uid: createHash('sha256').update('data-view:' + id).digest('hex').slice(0, 8), id,
  parent: id === 'data' ? null : id.slice(0, id.lastIndexOf('.')),
  name, description, state: 'planned', source: [], revision: '0'.repeat(40),
  updated_at: timestamp, fingerprint: 'pending', ...extra,
})
const types = architecture.modules.flatMap(owner => (owner.types ?? []).map(type => ({ owner, type })))
const targets = new Map(types.map(({ owner, type }) => [typeRefUri({ module: owner.id, name: type.name }), {
  id: 'data.' + owner.id.split('.')[1] + '.t-' + createHash('sha256').update(owner.id + ':' + type.name).digest('hex').slice(0, 8),
  name: type.name,
}]))
const groups = [...new Set(types.map(({ owner }) => owner.id.split('.')[1]))]
const root = module('data', text('视频平台数据结构', 'Video Platform Data Structures'), text('从 pi 生成的架构契约直接投影：业务实体、接口请求响应和事件。字段与 Schema 来自同一份设计；点击类型查看完整结构，连线表示真实类型引用。', 'Direct projection of the architecture contracts generated by pi. Entities, API payloads and events preserve their original fields; edges show actual type references.'))
const modules = [root]
for (const group of groups) {
  const owner = architecture.modules.find(owner => owner.id === 'bili.' + group)
  if (!owner) throw new Error('类型领域不存在：' + group)
  modules.push(module('data.' + group, owner.name, text('该领域的命名数据结构，保留原架构定义。', 'Named data structures from the original architecture.')))
}
for (const { owner, type } of types) {
  const target = targets.get(typeRefUri({ module: owner.id, name: type.name }))
  const schema = structuredClone(type.schema)
  const refs = collectSchemaRefs(schema)
  const deps = new Map()
  for (const ref of refs) {
    if (!ref.target) continue
    const linked = targets.get(typeRefUri(ref.target))
    if (!linked) throw new Error('缺少类型引用：' + ref.ref)
    const fragmentAt = ref.ref.indexOf('#')
    const fragment = fragmentAt === -1 ? '' : ref.ref.slice(fragmentAt)
    const keys = ref.path.split('/').slice(1).map(key => key.replace(/~1/g, '/').replace(/~0/g, '~'))
    let object = schema
    for (const key of keys.slice(0, -1)) object = object[key]
    object[keys.at(-1)] = typeRefUri({ module: linked.id, name: linked.name }) + fragment
    if (linked.id !== target.id) deps.set(linked.id, { kind: 'reference', to: linked.id, label: text('类型引用', 'Type reference') })
  }
  if (Object.hasOwn(schema, '$id')) schema.$id = typeRefUri({ module: target.id, name: target.name })
  modules.push(module(target.id, text(type.name, type.name), type.description, {
    source: [{ path: 'design/data/' + target.id.replaceAll('.', '/') + '.json' }],
    tags: [...(owner.tags ?? []), 'projection:data-contract'], apis: [],
    types: [{ ...type, schema }], deps: [...deps.values()],
  }))
}
const layouts = [
  { schema_version: 1, updated_at: timestamp, id: 'data', mode: 'grid', max_columns: 4, max_api_rows: 0, reading: text('按领域下钻，每个叶子是一种数据结构。图中展示真实 Schema 引用，不把接口 DTO 误称为数据库表。', 'Drill into a domain, then a named type. Edges show actual schema references; API DTOs are not database tables.'), order: groups.map(group => 'data.' + group) },
  ...groups.map(group => ({ schema_version: 1, updated_at: timestamp, id: 'data.' + group, mode: 'grid', max_columns: 4, max_api_rows: 0, reading: text('点击结构查看字段、必填项、枚举与完整 JSON Schema。', 'Open a type to inspect fields, required values, enums and full JSON Schema.'), order: modules.filter(module => module.parent === 'data.' + group).map(module => module.id) })),
]
const graph = { schema_version: 1, modules, layouts }
const tools = new Map((await createPromptManagerTools({ repoRoot: process.cwd() + '/project', dataDir: process.cwd() + '/normify-data', access: 'write' })).map(tool => [tool.name, tool]))
const current = await tools.get('normify_graph_get').execute()
if (!current.ok) throw new Error(JSON.stringify(current.errors))
const checked = await tools.get('normify_graph_validate').execute({ graph })
if (!checked.ok) throw new Error(JSON.stringify(checked.errors))
const result = await tools.get('normify_graph_put').execute({ graph, expect_digest: current.digest })
if (!result.ok) throw new Error(JSON.stringify(result.errors))
await writeFile(new URL('./data.json', import.meta.url), JSON.stringify(graph, null, 2) + '\n')
await writeFile(new URL('./diagrams.json', import.meta.url), JSON.stringify({ runner: 'pi', model: 'deepseek-v4-flash', architecture_modules: architecture.modules.length, architecture_apis: architecture.modules.reduce((n, module) => n + (module.apis ?? []).length, 0), data_types: types.length, data_view: '机械投影原架构 JSON Schema；不是单独生成的数据库 ER 模型', data_digest: result.digest }, null, 2) + '\n')
console.log(JSON.stringify({ ok: true, architecture_modules: architecture.modules.length, data_types: types.length, data_modules: modules.length, digest: result.digest }))
